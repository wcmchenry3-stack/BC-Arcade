"""Contract tests for the French and Spanish Daily Word lists (#3239).

The lists in backend/daily_word/words/ are generated by scripts/gen_romance_words.py and
are not served until #3240. These tests pin the file format #3240 / #3241 rely on.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

import pytest

_BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_BACKEND / "scripts"))

from _romance_curation import ANSWER_EXCLUDE
from _wordfold import fold, is_key
from gen_romance_words import parse_blocklist

WORDS = _BACKEND / "daily_word" / "words"
LANGS = ("fr", "es")
MIN_ANSWERS = 1000
MIN_VALID = 5000


def _lines(name: str) -> list[str]:
    return (WORDS / name).read_text(encoding="utf-8").splitlines()


def _blocklist_lines(lang: str) -> list[str]:
    out = []
    for line in _lines(f"answers_blocklist_{lang}.txt"):
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


@pytest.mark.parametrize("lang", LANGS)
@pytest.mark.parametrize("kind", ("answers", "valid"))
def test_every_line_is_a_lowercase_nfc_display_word_with_a_5_letter_key(lang, kind):
    for w in _lines(f"{kind}_{lang}.txt"):
        assert w == unicodedata.normalize("NFC", w), f"{w!r} is not NFC"
        assert w == w.lower() and w == w.strip() and w.isalpha(), w
        assert is_key(fold(w), lang), f"{w!r} folds to {fold(w)!r}"


@pytest.mark.parametrize("lang", LANGS)
@pytest.mark.parametrize("kind", ("answers", "valid"))
def test_fold_keys_are_unique_and_sorted(lang, kind):
    words = _lines(f"{kind}_{lang}.txt")
    keys = [fold(w) for w in words]
    assert len(keys) == len(set(keys)), "two display forms share a fold key"
    assert keys == sorted(keys)


def test_french_keys_never_contain_n_tilde_and_spanish_keep_it():
    assert not any("ñ" in fold(w) for w in _lines("valid_fr.txt"))
    assert any("ñ" in fold(w) for w in _lines("valid_es.txt"))
    assert any("ñ" in w for w in _lines("answers_es.txt"))


@pytest.mark.parametrize("lang", LANGS)
def test_every_answer_is_in_valid_with_the_same_display(lang):
    valid = set(_lines(f"valid_{lang}.txt"))
    missing = [w for w in _lines(f"answers_{lang}.txt") if w not in valid]
    assert not missing, missing[:20]


@pytest.mark.parametrize("lang", LANGS)
def test_no_blocklisted_or_excluded_word_is_an_answer(lang):
    blocked = parse_blocklist((WORDS / f"answers_blocklist_{lang}.txt").read_text("utf-8"))
    answers = {fold(w) for w in _lines(f"answers_{lang}.txt")}
    assert not answers & blocked
    assert not answers & ANSWER_EXCLUDE[lang]


@pytest.mark.parametrize("lang", LANGS)
def test_blocklist_lines_are_folded_5_letter_keys(lang):
    lines = _blocklist_lines(lang)
    assert len(lines) >= 100
    for line in lines:
        assert line == fold(line) and is_key(line, lang), line
    assert len(lines) == len(set(lines)), "duplicate blocklist entry"


@pytest.mark.parametrize("lang", LANGS)
def test_exclusions_are_folded_5_letter_keys(lang):
    for key in ANSWER_EXCLUDE[lang]:
        assert key == fold(key) and is_key(key, lang), key


@pytest.mark.parametrize("lang", LANGS)
def test_list_sizes_meet_the_minimums(lang):
    assert len(_lines(f"answers_{lang}.txt")) >= MIN_ANSWERS
    assert len(_lines(f"valid_{lang}.txt")) >= MIN_VALID


@pytest.mark.parametrize(
    ("lang", "words"),
    [
        # Lemmas, an irregular form, a ligature and a respelled Littré word.
        ("fr", ("était", "cœur", "poème", "pêche", "école")),
        ("es", ("árbol", "niños", "razón", "había", "puede", "dueño")),
    ],
)
def test_accented_display_forms_are_kept(lang, words):
    valid = set(_lines(f"valid_{lang}.txt"))
    for w in words:
        assert w in valid, w


def test_blocklisted_words_stay_valid_guesses():
    assert "merde" in _lines("valid_fr.txt")
    assert "matar" in _lines("valid_es.txt")

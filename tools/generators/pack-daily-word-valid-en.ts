/**
 * Packs the English Daily Word guess list into the module the app ships, so
 * guesses can be checked offline (#3230).
 *
 * Reads backend/daily_word/words/valid_en.txt and answers_en.txt (the server's
 * accepted set is their union, `_VALID_EN` in backend/daily_word/puzzle.py)
 * and writes frontend/src/game/daily_word/validWordsEn.generated.ts: every
 * word, sorted, joined with no separator (they are all five letters), so the
 * app can binary-search the string without building a Set. Re-run it after
 * regenerating either list; validWords.test.ts fails until you do.
 *
 * Usage (from the repo root):
 *   npx --prefix frontend tsx tools/generators/pack-daily-word-valid-en.ts
 */

import { readFileSync, writeFileSync } from "node:fs";

const WORDS_DIR = "backend/daily_word/words";
const OUTPUT_PATH = "frontend/src/game/daily_word/validWordsEn.generated.ts";
const WORD_LENGTH = 5;

function readList(file: string): string[] {
  return readFileSync(`${WORDS_DIR}/${file}`, "utf8")
    .split("\n")
    .map((w) => w.trim())
    .filter((w) => w !== "");
}

const words = [
  ...new Set([...readList("valid_en.txt"), ...readList("answers_en.txt")]),
].sort();
for (const w of words) {
  if (!/^[a-z]+$/.test(w) || w.length !== WORD_LENGTH) {
    throw new Error(
      `not a ${WORD_LENGTH}-letter a-z word: ${JSON.stringify(w)}`,
    );
  }
}

const content = `// Generated by tools/generators/pack-daily-word-valid-en.ts from
// backend/daily_word/words/valid_en.txt + answers_en.txt (#3230). Do not edit.
// ${words.length} sorted ${WORD_LENGTH}-letter words, concatenated.

export const VALID_EN_WORD_LENGTH = ${WORD_LENGTH};

export const VALID_EN_WORDS =
  "${words.join("")}";
`;

writeFileSync(OUTPUT_PATH, content);
console.log(
  `Wrote ${OUTPUT_PATH} (${words.length} words, ${content.length} bytes)`,
);
